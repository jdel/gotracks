export const locales: Record<string, Partial<Dict>> = { en, fr, it, de };

/** Locales offered in the settings picker. */
export const availableLocales = [
  { code: "en", label: "English", flag: "🇬🇧" },
  { code: "fr", label: "Français", flag: "🇫🇷" },
  { code: "it", label: "Italiano", flag: "🇮🇹" },
  { code: "de", label: "Deutsch", flag: "🇩🇪" },
];

export const LOCALE_KEY = "gt.locale";
const DEFAULT_LOCALE = "en";

export function isSupported(code: string): boolean {
  return availableLocales.some((l) => l.code === code);
}

/**
 * Reduces a locale tag to one there are translations for, mirroring the
 * server: a regional tag keeps only its language, and anything unknown
 * becomes the default.
 */
export function normaliseLocale(code: string | null | undefined): string {
  const base = (code ?? "").toLowerCase().trim().split(/[-_]/)[0];
  return isSupported(base) ? base : DEFAULT_LOCALE;
}

/**
 * The locale to use before any account preference is known.
 *
 * The sign-in and registration screens render without a session, so they have
 * no stored preference to read. A previous choice on this device wins, then
 * whatever the browser asks for, so someone arriving on a French browser gets
 * a French registration form without touching anything.
 */
export function initialLocale(): string {
  const stored = localStorage.getItem(LOCALE_KEY);
  if (stored && isSupported(stored)) return stored;
  return normaliseLocale(navigator.language);
}

/** Values interpolated into a string's {placeholders}. */
export type TParams = Record<string, string | number>;

/** A translate function: looks up a key and fills in any {placeholders}. */
export type TFunc = (key: Key, params?: TParams) => string;

/**
 * A count-aware translate function.
 *
 * Picks between a `<key>.one` and `<key>.other` entry by the plural rule of the
 * active language, and passes `count` in as a placeholder so the number can sit
 * inside the phrase. English is singular only for exactly one; French treats 0
 * as singular too ("0 note", not "0 notes").
 */
export type TnFunc = (count: number, key: string, params?: TParams) => string;

export function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    name in params ? String(params[name]) : whole,
  );
}

export function isPluralOne(locale: string, count: number): boolean {
  return locale === "fr" ? Math.abs(count) <= 1 : count === 1;
}

export interface I18nValue {
  t: TFunc;
  tn: TnFunc;
  locale: string;
  /** Changes the language for this device. Persisting it to the account is
   *  the caller's job — registration sends it, settings saves it. */
  setLocale: (code: string) => void;
}

const fallbackT: TFunc = (key, params) => interpolate(en[key], params);

export const I18nContext = createContext<I18nValue>({
  t: fallbackT,
  tn: (count, key, params) =>
    fallbackT(`${key}.other` as Key, { count, ...params }),
  locale: DEFAULT_LOCALE,
  setLocale: () => {},
});

/** useT returns the translate function for the active locale. */
export function useT(): TFunc {
  return useContext(I18nContext).t;
}

/** useTn returns the count-aware translate function. */
export function useTn(): TnFunc {
  return useContext(I18nContext).tn;
}

/** useLocale exposes the active language and a way to change it. */
export function useLocale() {
  const { locale, setLocale } = useContext(I18nContext);
  return { locale, setLocale };
}
